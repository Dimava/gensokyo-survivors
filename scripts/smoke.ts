import { newGame, activeRun, renderRun, renderMeta } from "../src/sim/game.ts";
const k = newGame("smoke");
console.log(renderMeta(k));
const r = k.dispatch("/", "run:start", { stage: "lake" });
console.log(r.ok, !r.ok && r.rejection);
const path = activeRun(k)!;
console.log(path, k.paths());
